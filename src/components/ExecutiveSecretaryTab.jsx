    return {
      count,
      grossRevenue,
      aov,
      cogsAmount,
      netProfit,
      topBranchName: topBranch[0],
      topBranchRevenue: topBranch[1],
      topProductName: topProduct[0],
      topProductUnits: topProduct[1],
      lowStockItemsCount: lowStockItems.length,
      lowStockItemsList: lowStockItems.slice(0, 3)
    };
