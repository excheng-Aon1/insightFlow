      id: 'tsk-1',
      title: tx('สั่งซื้อวัตถุดิบและสินค้าหมุนเวียนหลัก (SKU-01) เพิ่ม 250 ชิ้น', 'Reorder main inventory SKU-01 (+250 units) before stockout'),
