  // Trigger Autonomous Agent Refresh
  // -------------------------------------------------------------
  const handleTriggerAgentBriefing = () => {
    setAgentStatus('analyzing');
    hotToast.loading(tx('เลขา AI กำลังกวาดข้อมูลยอดขายและสต็อกสด...', 'AI Secretary is auditing live business records...'), { id: 'agent-run' });

    setTimeout(() => {
      setAgentStatus('ready');
      setLastBriefingTime(new Date().toLocaleTimeString('th-TH', { hour: '2-digit', minute: '2-digit' }));
      hotToast.success(tx('เลขา AI ปรับปรุงรายงานสรุปงานผู้บริหารเสร็จสิ้น!', 'Daily Executive Briefing refreshed!'), {
        id: 'agent-run'
      });
    }, 900);
  };

